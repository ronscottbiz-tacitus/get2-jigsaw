export const fullSrcForKey = (key: string) => imgFull(key);
export const posterSrcForKey = (key: string) => poster(key);

export const DEFAULT_IMAGE_SRC = IMAGES[0].full; // Mountain Valley
export const DEFAULT_VIDEO_SRC = VIDEOS[1].src; // Balloons — matches the prototype default

export function imageBySrc(src: string): ImageItem | undefined {
  return IMAGES.find((i) => i.full === src);
}
export function videoBySrc(src: string): VideoItem | undefined {
  return VIDEOS.find((v) => v.src === src);
}

export function imagesByCategory(): [Category, ImageItem[]][] {
  return CATEGORIES.map((cat) => [cat, IMAGES.filter((i) => i.category === cat)]);
}

/** Label for a puzzle currently loaded from `src` (image or video). */
export function labelForSrc(contentType: ContentType, src: string): string {
  if (contentType === 'video') return videoBySrc(src)?.name ?? 'Live';
  return imageBySrc(src)?.name ?? 'Library';
}
