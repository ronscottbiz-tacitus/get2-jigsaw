/**
 * Curated content library.
 *
 * Everything the app can turn into a puzzle lives here as data. Images are
 * grouped into six categories; each has a full-res source (used as the puzzle
 * image) and a thumbnail (used in grids and the picker). "Live" clips are short
 * looping videos with a still poster frame for use anywhere a `<video>` element
 * shouldn't autoplay (marketing grid, picker).
 *
 * Free vs Premium: the `tier` field gates visibility. Premium is waitlist-only
 * for now (no purchase flow) — see `src/content/tiers.ts`. Flip a `tier` here to
 * move an item between tiers; add rows to grow the library toward the 30–50
 * target. `curated: true` marks assets that are real curated originals (Google
 * AI Studio stills / Morph Studio clips) rather than stand-ins.
 */
import type { ContentType } from '../game/types';

export type Tier = 'free' | 'premium';

export const CATEGORIES = [
  'Landscapes / Nature',
  'Animals / Wildlife',
  'Architecture / Cityscapes',
  'Space / Cosmic',
  'Abstract / Pattern Art',
  'Florals / Botanical',
] as const;
export type Category = (typeof CATEGORIES)[number];

export interface ImageItem {
  kind: 'image';
  key: string;
  name: string;
  category: Category;
  tier: Tier;
  curated: boolean;
  full: string;
  thumb: string;
}

export interface VideoItem {
  kind: 'video';
  key: string;
  name: string;
  tier: Tier;
  curated: boolean;
  src: string;
  poster: string;
}

export type LibraryItem = ImageItem | VideoItem;

/**
 * Placeholder assets are `.svg` (generated by `scripts/gen-placeholders.mjs`).
 * When the real curated originals land, drop them in with the same base names
 * and change `IMG_EXT` to `'jpg'` — nothing else needs to move.
 */
export const IMG_EXT: 'svg' | 'jpg' = 'jpg';

const imgFull = (key: string) =>
  `/uploads/puzzle-library/full/puz_${key}.${IMG_EXT}`;
const imgThumb = (key: string) =>
  `/uploads/puzzle-library/thumbs/puz_${key}.${IMG_EXT}`;
const poster = (key: string) =>
  `/uploads/puzzle-library/posters/poster_${key}.${IMG_EXT}`;

function image(
  key: string,
  name: string,
  category: Category,
  tier: Tier,
): ImageItem {
  return {
    kind: 'image',
    key,
    name,
    category,
    tier,
    curated: true,
    full: imgFull(key),
    thumb: imgThumb(key),
  };
}

